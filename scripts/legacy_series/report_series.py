"""Summarize this trial without changing analyses or the series registry.

Writes series-report.txt and voice-continuity.csv in the required --root directory.
Exit 0: all seven analyses present and mechanical checks pass; 1: input/check
failure; 2: incomplete trial. Outstanding review decisions remain explicit even
with exit 0. --overwrite replaces only this helper's own generated reports.
"""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
import csv
from datetime import datetime, timezone
import io
import json
from pathlib import Path
import sys
import unicodedata

PROJECT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(PROJECT))
from epub_audiobook.pipeline import fingerprint
from epub_audiobook.series import validate_registry
from audit_continuity import audit_book

TITLE = "Soulship series processing report (generated by report_series.py)"
FIELDS = ["entity_kind", "character_id", "voice_ids", "names", "appearances",
          "voice_id_consistent", "voice_profile_consistent", "normalized_alias_collisions",
          *[f"book_{number:02}_name" for number in range(1, 8)]]
IDENTITY_KINDS = {"identity", "identity_merge", "identity_consensus", "series_identity", "series_narrator"}


def read(path):
    return json.loads(path.read_text(encoding="utf-8"))


def normalized(value):
    return " ".join(unicodedata.normalize("NFKC", value).casefold().split())


def safe_cell(value):
    text = str(value)
    return "'" + text if text.lstrip().startswith(("=", "+", "-", "@")) else text


def brief(value, limit=700):
    text = " ".join(str(value).split())
    return text if len(text) <= limit else text[:limit - 3] + "..."


def references(values, limit=8):
    values = list(dict.fromkeys(str(value) for value in values))
    return ", ".join(values[:limit]) + (f" (+{len(values) - limit} more)" if len(values) > limit else "") or "none"


def semantic_history(document):
    """Summarize each audit scope; totals count events, never current errors."""
    provenance = document["provenance"]
    history = provenance.get("attribution_review_history", [])
    current = provenance.get("attribution_review")
    records = [*history, *([current] if current is not None else [])]
    if not records:
        return ["Semantic model review: no recorded passes."], []
    source_hash, script_hash = fingerprint(document["source"]), fingerprint(document["segments"])
    cast_hash = fingerprint(document["cast"])
    source_ids = {block["id"] for block in document["source"]["blocks"]}
    totals, all_applied, lines, errors = Counter(), set(), [], []
    for index, record in enumerate(records, 1):
        reference = (f"provenance.attribution_review_history[{index - 1}]" if index <= len(history)
                     else "provenance.attribution_review")
        targets = [identity for scan in record.get("scans", []) for identity in scan.get("target_block_ids", [])]
        target_ids = set(targets)
        changes = record.get("changes", [])
        proposed = len(changes)
        applied = sum(change.get("status") == "applied" for change in changes)
        unresolved = sum(change.get("status") == "unresolved" for change in changes)
        if (record.get("source_fingerprint") != source_hash or not target_ids <= source_ids
                or len(targets) != len(target_ids)):
            errors.append(f"Semantic review pass {index} has invalid source binding or coverage")
        if (proposed != applied + unresolved
                or any(record.get(key) != value for key, value in
                       (("proposed_blocks", proposed), ("applied_blocks", applied), ("unresolved_blocks", unresolved)))):
            errors.append(f"Semantic review pass {index} counts do not match its change records")
        scope = record.get("scope", {})
        mode = scope.get("mode")
        if mode == "all_blocks" and target_ids != source_ids:
            errors.append(f"Semantic review pass {index} claims all blocks but scan coverage differs")
        if mode == "target_blocks" and set(scope.get("target_block_ids", [])) != target_ids:
            errors.append(f"Semantic review pass {index} target scope differs from scan coverage")
        if scope and (scope.get("reviewed_blocks") != len(target_ids)
                      or scope.get("total_source_blocks") != len(source_ids)):
            errors.append(f"Semantic review pass {index} scope counts differ from source/scan coverage")
        label = "all source blocks" if target_ids == source_ids and target_ids else "targeted blocks"
        if not scope:
            label += " (inferred from recorded scan targets)"
        totals.update(proposed=proposed, applied=applied, unresolved=unresolved)
        all_applied.update(change["block_id"] for change in changes if change.get("status") == "applied")
        lines.append(f"  Pass {index}: {label}, {len(target_ids)}/{len(source_ids)} blocks; "
                     f"{len(record.get('scans', []))} original batches; proposed={proposed}, applied={applied}, "
                     f"unresolved-at-that-pass={unresolved}; cast={'current' if record.get('cast_fingerprint') == cast_hash else 'historical'}; "
                     f"output script matches current={'yes' if record.get('output_script_fingerprint') == script_hash else 'no'}.")
        lines.append(f"    Record: {reference}" +
                     (f"; target references: {references(targets)}" if target_ids != source_ids else ""))
    header = (f"Semantic model review history: {len(records)} passes; {totals['proposed']} proposed / "
              f"{totals['applied']} applied / {totals['unresolved']} unresolved block-decision occurrences; "
              f"{len(all_applied)} distinct blocks changed across passes.")
    return [header, "Counts above include repeated blocks and past disagreements; they are not current assignment-error counts.", *lines], errors


def independent_source_audit(directory, document):
    """Use only the exact current analysis audit; retain its qualified scope."""
    path = directory / "final-source-audit.json"
    if not path.is_file():
        path = directory / "post-review-source-audit.json"
    if not path.is_file():
        return ["Independent final source audit: not present; no current semantic conclusion inferred."], []
    audit = read(path)
    bindings = [("source_fingerprint", fingerprint(document["source"]))]
    analysis_key = "analysis_fingerprint" if "analysis_fingerprint" in audit else "reviewed_analysis_fingerprint"
    bindings.append((analysis_key, fingerprint(document)))
    if "cast_fingerprint" in audit:
        bindings.append(("cast_fingerprint", fingerprint(document["cast"])))
    mismatches = [key for key, actual in bindings if audit.get(key) != actual]
    lines = [f"Independent final source audit: {path}"]
    if mismatches:
        return [*lines, "STALE OR UNBOUND: " + ", ".join(mismatches) +
                "; its findings are not reported as current."], ["Final source audit fingerprint mismatch: " + ", ".join(mismatches)]
    lines.append(f"  Fingerprints: match current analysis/source" +
                 ("/cast" if "cast_fingerprint" in audit else "") +
                 f"; status={brief(audit.get('status', 'unspecified'), 100)}. Independent automated review, not human approval.")
    scope = audit.get("scope")
    if isinstance(scope, dict):
        description = scope.get("description", "Scope details recorded in audit file.")
    elif isinstance(scope, str):
        description = scope
    else:
        description = "Specified correction verification and unintended word-role-change checks; not a complete independent semantic reread."
    lines.append("  Scope: " + brief(description))
    checks = audit.get("checks", {})
    if "prior_findings_verified" in checks:
        lines.append(f"  Reference findings checked: {checks['prior_findings_verified']}; "
                     f"remaining reference word-role errors: {len(checks.get('prior_span_word_role_errors', []))}; "
                     f"changed blocks checked: {checks.get('changed_blocks', 'unspecified')}.")
    remaining = audit.get("current_assignment_review_needs")
    # Some source audits summarize findings in an object and enumerate current
    # disagreements separately. Only row lists support the legacy fallback.
    finding_rows = audit.get("findings", [])
    findings = [row for row in finding_rows
                if isinstance(row, dict) and row.get("resolved") is False] if isinstance(finding_rows, list) else []
    current_details = audit.get("current_assignment_review_need_details", findings)
    if type(remaining) is int:
        lines.append(f"  Current assignment disagreements needing review within this audit's scope: {remaining}; "
                     f"references: {references(row.get('block_id', row.get('id', 'unspecified')) for row in current_details)}.")
    else:
        lines.append("  Current assignment-review count: not separately enumerated; no zero-error inference.")
    historical = audit.get("historical_disagreement_records", [])
    if historical:
        issue_map = {issue["id"]: issue for issue in document["issues"]}
        retained = sum(issue_map.get(row.get("issue_id"), {}).get("resolved") is False for row in historical)
        lines.append(f"  Historical disagreements identified separately by this audit: {len(historical)}; "
                     f"{retained} issue flags remain unresolved in the current analysis. Their assignments were corrected "
                     f"by later reviewed passes; they are not additional current disagreement counts.")
        lines.append("    Historical references: " + references(row.get("block_id", row.get("issue_id", "unspecified")) for row in historical))
    uncertainties = audit.get("preserved_uncertainties")
    if isinstance(uncertainties, list):
        lines.append(f"  Additional preserved source/identity uncertainty records: {len(uncertainties)}; see audit file. "
                     "These are separate from the focused current-disagreement count.")
    elif audit.get("uncertainty_check"):
        lines.append("  Preserved uncertainty checks: " + references(audit["uncertainty_check"]))
    if audit.get("conclusion"):
        lines.append("  Audit conclusion: " + brief(audit["conclusion"], 900))
    return lines, []


def summarize(root):
    inventory = read(root / "inventory.json")
    if sorted(item["number"] for item in inventory) != list(range(1, 8)):
        raise ValueError("Inventory must list each book from 1 through 7 exactly once")
    lines = [TITLE, f"Generated: {datetime.now(timezone.utc).isoformat()}", f"Root: {root}", "",
             "Stable IDs and three-reviewer agreement do not establish literary identity accuracy.",
             "All outputs remain drafts, not human-approved; READY denotes only the mechanical/review gate.",
             "Drafts require review; duplicate names/aliases below are candidates, never automatic merges.", ""]
    failures, missing = [], []
    registry_path = root / "series-cast.json"
    registry = None
    if registry_path.is_file():
        try:
            registry = read(registry_path)
            validate_registry(registry)
        except (ValueError, KeyError, TypeError):
            failures.append("Series registry invalid")
            registry = None
    lines.append(f"Registry: {registry['series_id']} ({len(registry['books'])} published books)" if registry else "Registry: unavailable")
    published = {book["source_fingerprint"]: book for book in registry["books"]} if registry else {}
    entities, alias_ids, voice_profiles = {}, defaultdict(set), defaultdict(set)
    completed_sources = set()
    details = []
    lines += ["", "BOOKS", "Number | State | Characters | Voices | Segments | Review items | Mechanical errors | Published"]
    for item in sorted(inventory, key=lambda entry: entry["number"]):
        number, path = item["number"], root / f"book-{item['number']:02}" / "analysis.json"
        if not path.is_file():
            missing.append(number)
            lines.append(f"{number:02} | MISSING | - | - | - | - | - | no")
            continue
        try:
            document = read(path)
            audit = audit_book(root, number)
            if "readiness" not in audit:
                raise ValueError("Analysis failed contract validation")
            source_hash = fingerprint(document["source"])
            completed_sources.add(source_hash)
            errors = list(audit["errors"])
            if source_hash != item["source_fingerprint"]:
                errors.append({"code": "inventory_source_fingerprint_mismatch"})
            saved = published.get(source_hash)
            if saved and saved["cast"] != document["cast"]:
                errors.append({"code": "published_cast_differs_from_analysis"})
            failures.extend(f"Book {number:02}: {entry['code']}" for entry in errors)
            state = "INVALID" if errors else "READY" if audit["readiness"]["ready"] else "DRAFT"
            cast = document["cast"]
            lines.append(f"{number:02} | {state} | {len(cast['characters'])} | {len(cast['voices'])} | "
                         f"{len(document['segments'])} | {audit['readiness']['review_count']} | {len(errors)} | {'yes' if saved else 'no'}")
            details += ["", f"Book {number:02}: {item['title']}", f"Analysis: {path}",
                        f"Source fingerprint: {source_hash}",
                        "Mechanical audit covers source preservation, accepted consensus evidence, retained voice profiles, and bundle hashes.",
                        f"Reused character IDs: {len(audit.get('reused_characters', []))}; "
                        f"unresolved series matches: {len(audit.get('unresolved_identity_candidates', []))}; "
                        f"identity review candidates: {len(audit.get('review_candidates', []))}."]
            unresolved = [issue for issue in document["issues"] if not issue["resolved"]]
            counts = Counter(issue["kind"] for issue in unresolved)
            details.append("Unresolved issue types: " + (", ".join(f"{key}={value}" for key, value in sorted(counts.items())) or "none"))
            review_lines, review_errors = semantic_history(document)
            source_audit_lines, source_audit_errors = independent_source_audit(path.parent, document)
            details.extend(review_lines + source_audit_lines)
            failures.extend(f"Book {number:02}: {message}" for message in review_errors + source_audit_errors)
            identity_issues = [issue for issue in unresolved if issue["kind"] in IDENTITY_KINDS]
            for issue in identity_issues:
                inherited = issue.get("series_origin", {}).get("kind") == "inherited_series_review"
                details.append(f"  {'Inherited' if inherited else 'Retained local'} identity issue {issue['id']} "
                               f"[{issue['kind']}] target={issue['target']}: {issue['reason']}")
            for candidate in audit.get("review_candidates", []):
                details.append("  Review candidate: " + json.dumps(candidate, ensure_ascii=False, sort_keys=True))
            for voice in cast["voices"]:
                voice_profiles[voice["id"]].add(fingerprint({"description": voice["description"],
                    "traits": [(trait["name"],trait["value"]) for trait in voice["traits"]]}))
            for character in cast["characters"]:
                identity = character["id"]
                entry = entities.setdefault(("character", identity), {"id": identity, "names": set(), "voices": set(), "books": {}})
                entry["names"].update([character["name"], *character["aliases"]])
                entry["voices"].add(character["voice_id"])
                entry["books"][number] = character["name"]
                for value in [character["name"], *character["aliases"]]:
                    if alias := normalized(value):
                        alias_ids[alias].add(identity)
            for role in cast["roles"]:
                if role["kind"] == "narration":
                    key = ("narration_voice", role["voice_id"])
                    entry = entities.setdefault(key, {"id": role["character_id"] or "", "names": set(), "voices": set(), "books": {}})
                    entry["voices"].add(role["voice_id"])
                    entry["names"].add(role["id"])
                    entry["books"][number] = role["id"]
        except (OSError, ValueError, KeyError, TypeError, AttributeError) as exc:
            failures.append(f"Book {number:02}: unreadable or invalid analysis/audit input ({type(exc).__name__})")
            lines.append(f"{number:02} | INVALID | - | - | - | - | input failure | unknown")
    collisions = {alias: identities for alias, identities in alias_ids.items() if len(identities) > 1}
    lines += details + ["", "DUPLICATE NORMALIZED NAMES/ALIASES (review only)"]
    lines += [f"{alias}: {'; '.join(sorted(identities))}" for alias, identities in sorted(collisions.items())] or ["None found among completed analyses."]
    lines += ["", "IDENTITY AND VOICE MATRIX", "See voice-continuity.csv; blank book cells mean absent from that completed cast or an incomplete book.",
              "Narration rows group by voice ID; they do not prove that separate narration roles are the same identity."]
    csv_stream = io.StringIO(newline="")
    writer = csv.writer(csv_stream)
    writer.writerow(FIELDS)
    for (kind, _), entry in sorted(entities.items()):
        consistent = len(entry["voices"]) == 1
        profiles_ok = all(len(voice_profiles[voice]) == 1 for voice in entry["voices"])
        if kind == "character" and not consistent:
            failures.append(f"Character {entry['id']} has multiple voice IDs")
        if not profiles_ok:
            failures.append(f"Voice profile changed for {'; '.join(sorted(entry['voices']))}")
        row = [kind, entry["id"], "; ".join(sorted(entry["voices"])), "; ".join(sorted(entry["names"])),
               "; ".join(str(number) for number in sorted(entry["books"])), consistent, profiles_ok,
               "; ".join(alias for alias, identities in sorted(collisions.items()) if kind == "character" and entry["id"] in identities),
               *[entry["books"].get(number, "") for number in range(1, 8)]]
        writer.writerow([safe_cell(value) for value in row])
    unpublished = completed_sources - published.keys()
    if unpublished:
        lines += ["", f"Completed analyses awaiting registry publication: {len(unpublished)}."]
    lines += ["", "Mechanical failures:"] + (sorted(set(failures)) or ["None found in completed analyses."])
    lines += ["", f"Missing analyses: {', '.join(map(str, missing)) or 'none'}.",
              "No analyses, registries, source documents, or provider settings were changed."]
    return "\n".join(lines) + "\n", csv_stream.getvalue(), 1 if failures else 2 if missing or unpublished else 0


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, required=True, help="Existing legacy seven-book run directory")
    parser.add_argument("--overwrite", action="store_true")
    args = parser.parse_args()
    root = args.root.resolve()
    outputs = [(root / "series-report.txt", TITLE), (root / "voice-continuity.csv", ",".join(FIELDS))]
    for path, header in outputs:
        if path.is_symlink() or (path.exists() and (not args.overwrite or path.read_text(encoding="utf-8").splitlines()[:1] != [header])):
            parser.error(f"Refusing to replace {path}; --overwrite only replaces this helper's generated reports")
    try:
        report, table, status = summarize(root)
    except (OSError, ValueError, KeyError, TypeError) as exc:
        parser.error(f"Unable to read inventory/registry: {type(exc).__name__}")
    for (path, _), content in zip(outputs, (report, table)):
        with path.open("w" if args.overwrite else "x", encoding="utf-8", newline="") as stream:
            stream.write(content)
        print(path)
    return status


if __name__ == "__main__":
    raise SystemExit(main())
